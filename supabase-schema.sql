create table if not exists public.logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  log_date date not null,
  orders int not null default 0,
  fee numeric not null default 0,         -- upah antar
  tip numeric not null default 0,         -- tip/bonus
  cod_due numeric not null default 0,     -- total nilai COD (yg Shopee talangi)
  cod_received numeric not null default 0,-- uang tunai dari customer (kotor)
  change_out numeric not null default 0,  -- kembalian yg kamu keluarkan
  bill_paid numeric not null default 0,   -- bayar tagihan Shopee
  bill_from text not null default 'cash', -- cash | wallet
  fuel numeric not null default 0,
  other_exp numeric not null default 0,
  cash_start numeric not null default 0,
  wallet_start numeric not null default 0,
  notes text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.settings (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  data jsonb not null default '{}',
  updated_at timestamptz not null default now()
);
alter table public.logs enable row level security;
alter table public.settings enable row level security;
create policy "logs own" on public.logs for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "settings own" on public.settings for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
